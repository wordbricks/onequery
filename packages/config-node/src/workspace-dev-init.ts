import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";

import type { WorkspaceDevSecretsFile } from "@onequery/config/workspace-dev";

import { resolveWorkspaceDevPaths } from "./workspace-dev";

export interface WorkspaceDevSecretsInitResult {
  readonly created: boolean;
  readonly path: string;
}

function createBase64Secret(bytes: number): string {
  return randomBytes(bytes).toString("base64");
}

function createBase64UrlSecret(bytes: number): string {
  return randomBytes(bytes).toString("base64url");
}

function createGeneratedWorkspaceDevSecrets(): WorkspaceDevSecretsFile {
  return {
    auth: {
      secret: createBase64UrlSecret(32),
    },
    connectors: {
      enrollment_token: createBase64UrlSecret(32),
    },
    crypto: {
      master_encryption_key: createBase64Secret(32),
    },
  };
}

function renderWorkspaceDevSecretsFile(
  secrets: WorkspaceDevSecretsFile
): string {
  return [
    "# Generated by OneQuery local bootstrap.",
    "# This file is local-only and intentionally gitignored.",
    "",
    "[auth]",
    `secret = ${JSON.stringify(secrets.auth.secret)}`,
    "",
    "[crypto]",
    `master_encryption_key = ${JSON.stringify(secrets.crypto.master_encryption_key)}`,
    "",
    "[connectors]",
    `enrollment_token = ${JSON.stringify(secrets.connectors.enrollment_token)}`,
    "",
  ].join("\n");
}

export function ensureWorkspaceDevSecretsFileSync(
  input: {
    readonly rootDir?: string;
  } = {}
): WorkspaceDevSecretsInitResult {
  const { secretsPath } = resolveWorkspaceDevPaths(input.rootDir);

  if (existsSync(secretsPath)) {
    return {
      created: false,
      path: secretsPath,
    };
  }

  mkdirSync(dirname(secretsPath), {
    recursive: true,
  });
  writeFileSync(
    secretsPath,
    renderWorkspaceDevSecretsFile(createGeneratedWorkspaceDevSecrets()),
    "utf8"
  );

  return {
    created: true,
    path: secretsPath,
  };
}
